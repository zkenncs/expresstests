document.addEventListener('DOMContentLoaded', function() {
  const elems = document.querySelectorAll('.autocomplete');
  const instances = M.Autocomplete.init(elems, {
    // specify options here
    minLength: 0, // shows instantly
    isMultiSelect: true,
    data: {
      "Apple" : null,
      "Microsoft": null,
      "Google": 'https://placehold.it/250x250'
    }
  });
});

const searchInput = document.getElementById("autocomplete-input");
const searchButton = document.getElementById("acButton");

searchInput.addEventListener('keydown', function(e) {
    if (e.key === 'Enter' ) {
      // Find the dropdown container generated by Materialize for this input
      let dropdown = searchInput.nextElementSibling; // Usually the <ul> container
      if (dropdown && dropdown.classList.contains('autocomplete-content')) {
        // Grab the first visible <li> option that isn't hidden
        let firstOption = dropdown.querySelector('li:not(.hide)');
        
        if (firstOption) {
          e.preventDefault(); // Stop default form submission behavior
          firstOption.click(); // Programmatically click it to trigger onAutocomplete
        }
      }
    }
});